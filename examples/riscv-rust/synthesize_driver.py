def generate_registers(spec):
    regs = []
    for reg in spec.get("registers", []):
        name = reg["name"]
        offset = reg["offset"]
        regs.append(f"const {name}: u32 = {offset};")
        if "bits" in reg:
            for bit_pos, bit_desc in reg["bits"].items():
                bit_name = bit_desc.split(" - ")[0].split(" (")[0]
                mask = 1 << int(bit_pos)
                regs.append(f"const {name}_{bit_name}: u32 = 0x{mask:02X};")
    return "\n".join(regs)

def synthesize(device_type_id, output_elf):
    # Mapping
    specs = {
        0: ("uart_16550.json", UART_TEMPLATE, "jit_driver.ld"),
        1: ("framebuffer.json", FB_TEMPLATE, "jit_driver_fb.ld"),
        2: ("virtio_blk.json", VIRTIO_BLK_TEMPLATE, "jit_driver_virtio_blk.ld"),
        3: ("virtio_net.json", VIRTIO_NET_TEMPLATE, "jit_driver_virtio_net.ld"),
    }
    
    if device_type_id not in specs:
        print(f"Error: Unsupported device type {device_type_id}")
        sys.exit(1)
        
    spec_file, template, ld_script = specs[device_type_id]
    
    # Paths
    base_dir = os.path.dirname(os.path.abspath(__file__))
    spec_path = os.path.join(base_dir, "device_specs", spec_file)
    ld_path = os.path.join(base_dir, ld_script)
    
    with open(spec_path, "r") as f:
        spec = json.load(f)
        
    # Generate source
    registers_code = generate_registers(spec)
    
    header = COMMON_HEADER.format(
        device_name=spec["device_name"],
        device_type=spec["device_type"]
    )
    
    source_code = template.format(
        common_header=header,
        device_name=spec["device_name"],
        registers=registers_code
    )
    
    rs_path = output_elf.replace(".elf", ".rs")
    with open(rs_path, "w") as f:
        f.write(source_code)
        
    # Compile
    cmd = [
        "rustc",
        "--target", "riscv32imac-unknown-none-elf",
        "-C", f"link-arg=-T{ld_path}",
        "-C", "opt-level=z",
        "-C", "panic=abort",
        "-o", output_elf,
        rs_path
    ]
    
    print(f"Compiling synthesized driver: {' '.join(cmd)}")
    result = subprocess.run(cmd, capture_output=True, text=True)
    if result.returncode != 0:
        print("Compilation failed!")
        print(result.stderr)
        sys.exit(1)
        
    print(f"Successfully synthesized {output_elf}")

if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("device_type", type=int)
    parser.add_argument("output_elf")
    args = parser.parse_args()
    
    synthesize(args.device_type, args.output_elf)
